//! A test-only plugin: the loader is exercised against a *real* shared object,
//! built by `cargo rustc --crate-type cdylib`, not against a mock of itself.
//!
//! That matters because the things that can go wrong at this boundary are
//! exactly the things a mock cannot reproduce: the symbol not being exported,
//! the fat-pointer handover, and the ABI number being read before the pointer it
//! guards is used. The `wrong-abi` feature builds the same crate answering with
//! a number the daemon cannot speak, so the refusal is a real `dlopen` of a real
//! file.
//!
//! Nothing here is shipped: the crate is `publish = false`, is never a
//! dependency of anything, and is only ever built into a `cdylib` by
//! `crates/tpmd/tests/plugin_loader.rs`.

#![deny(unsafe_code)]
#![warn(missing_docs)]

use std::path::Path;

use async_trait::async_trait;
use tpmd_backend::{Backend, BackendError, BackendFactory, Owner};
use tpmd_proto::{Algorithm, KeyId, KeyInfo, SecurityLevel, Signature};

/// The plugin's factory: it names itself, and opening it yields [`FixtureBackend`].
pub struct FixtureFactory;

#[async_trait]
impl BackendFactory for FixtureFactory {
    fn name(&self) -> &'static str {
        "fixture"
    }

    async fn open(&self, _state_dir: &Path) -> Result<Box<dyn Backend>, BackendError> {
        Ok(Box::new(FixtureBackend))
    }
}

/// A backend that exists to prove the trait object crossed the boundary intact.
///
/// It advertises the weakest level and refuses every operation, which is enough
/// to show that a *call* through the plugin's own code reaches the plugin's own
/// code — a name alone would only prove the factory was constructed.
pub struct FixtureBackend;

const LEVELS: &[SecurityLevel] = &[SecurityLevel::File];
const ALGORITHMS: &[Algorithm] = &[Algorithm::EcdsaP256Sha256];

#[async_trait]
impl Backend for FixtureBackend {
    fn name(&self) -> &'static str {
        "fixture"
    }

    fn algorithms(&self) -> &'static [Algorithm] {
        ALGORITHMS
    }

    fn levels(&self) -> &'static [SecurityLevel] {
        LEVELS
    }

    async fn provision(
        &self,
        _owner: &Owner,
        _algorithm: Algorithm,
        _level: SecurityLevel,
    ) -> Result<KeyInfo, BackendError> {
        Err(only_a_fixture())
    }

    async fn identify(&self, _owner: &Owner, _key_id: &KeyId) -> Result<KeyInfo, BackendError> {
        Err(only_a_fixture())
    }

    async fn sign(
        &self,
        _owner: &Owner,
        _key_id: &KeyId,
        _message: &[u8],
    ) -> Result<Signature, BackendError> {
        Err(only_a_fixture())
    }

    async fn destroy(&self, _owner: &Owner, _key_id: &KeyId) -> Result<(), BackendError> {
        Err(only_a_fixture())
    }
}

fn only_a_fixture() -> BackendError {
    BackendError::Unavailable("the loader fixture holds no keys".to_owned())
}

// The ordinary plugin entry point, generated by the boundary macro.
#[cfg(not(feature = "wrong-abi"))]
tpmd_plugin::export_backend!(FixtureFactory);

/// The entry point of a plugin from a *different* build: everything is right
/// except that it claims a boundary this daemon does not speak.
///
/// Hand-written rather than generated, so the only thing under test is the
/// version check — the factory it offers is the real one.
#[cfg(feature = "wrong-abi")]
#[allow(unsafe_code)]
#[unsafe(no_mangle)]
pub extern "C" fn tpmd_plugin_entry() -> tpmd_plugin::Entry {
    extern "C" fn make() -> *mut Box<dyn tpmd_plugin::BackendFactory> {
        tpmd_plugin::boxed(FixtureFactory)
    }
    tpmd_plugin::Entry {
        abi: tpmd_plugin::ABI_VERSION + 1,
        make,
    }
}
